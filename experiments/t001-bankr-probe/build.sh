#!/usr/bin/env bash
# Rebuild x402/breakra-t001-lib/index.ts as ONE self-contained file (no imports, no npm deps).
# Rev 2: Bankr returned a blank 500 for a bundle ending in `export { handler as default }`.
# The working probe uses the literal `export default async function handler(req)`, so the
# bundle's internal handler is renamed and re-exported in exactly that form.
set -euo pipefail
cd "$(dirname "$0")/lib-src"
bun install >/dev/null 2>&1
out=../x402/breakra-t001-lib/index.ts
tmp=$(mktemp)
bun build index.ts --target=bun --format=esm --outfile "$tmp" >/dev/null
python3 - "$tmp" "$out" <<'PY'
import sys, re
src = open(sys.argv[1]).read()
tail = re.search(r"export\s*\{\s*handler as default\s*\};?\s*$", src)
assert tail, "unexpected bundle tail"
src = src[:tail.start()]
assert src.count("async function handler(") == 1, "expected exactly one handler"
src = src.replace("async function handler(", "async function __t001LibHandler(")
header = ("// @ts-nocheck\n"
          "// GENERATED by build.sh from lib-src/index.ts with api-smart-diff 1.0.6 inlined "
          "(MIT, (C) Damir Yusipov). Do not edit.\n")
footer = ("\nexport default async function handler(req: Request): Promise<Response> {\n"
          "  return __t001LibHandler(req);\n}\n")
open(sys.argv[2], "w").write(header + src + footer)
PY
rm -f "$tmp"
echo "wrote $out ($(wc -c < "$out") bytes)"

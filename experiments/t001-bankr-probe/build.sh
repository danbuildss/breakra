#!/usr/bin/env bash
# Rebuild x402/breakra-t001-lib/index.ts as ONE self-contained file (no imports, no npm deps).
set -euo pipefail
cd "$(dirname "$0")/lib-src"
bun install --frozen-lockfile >/dev/null 2>&1 || bun install >/dev/null
out=../x402/breakra-t001-lib/index.ts
bun build index.ts --target=bun --format=esm --outfile /tmp/t001-lib.js >/dev/null
{ echo "// @ts-nocheck"; echo "// GENERATED by build.sh from lib-src/index.ts with api-smart-diff 1.0.6 inlined (MIT, (C) Damir Yusipov). Do not edit."; cat /tmp/t001-lib.js; } > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"

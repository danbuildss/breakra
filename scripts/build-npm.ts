/**
 * Builds the npm package's executable (D-041): dist/npm/cli.js, one self-contained ESM file for Node >= 20
 * (CLI + MCP server + engine + bundled api-smart-diff and yaml), so `npx breakra` installs no dependencies.
 * Not minified, so anyone can read what they run. The Bankr handler is built separately (scripts/build.ts).
 */
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const outDir = join(root, "dist/npm");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const result = await Bun.build({
  entrypoints: [join(root, "src/bin.ts")],
  target: "node",
  format: "esm",
  minify: false,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
let code = await (result.outputs[0] as Blob).text();
code = code.replace(/^#!.*\n/, "");
if (/\bBun\.(?!YAML)/.test(code))
  throw new Error("npm bundle must not depend on Bun APIs (other than the optional Bun.YAML check)");

// Third-party code bundled into cli.js, with its licence text (all permissive).
const BUNDLED = ["api-smart-diff", "allof-merge", "json-crawl", "yaml"];
const notices = BUNDLED.map((name) => {
  const meta = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8"));
  const licence = readFileSync(join(root, "node_modules", name, "LICENSE"), "utf8").trim();
  return `## ${name} ${meta.version} (${meta.license})\n\n${licence}\n`;
});

mkdirSync(outDir, { recursive: true });
const header = `#!/usr/bin/env node\n// breakra ${pkg.version}: GENERATED by scripts/build-npm.ts from https://github.com/danbuildss/breakra (MIT).\n// Bundles ${BUNDLED.join(", ")}; licences in THIRD_PARTY_NOTICES.md.\n`;
writeFileSync(join(outDir, "cli.js"), header + code);
chmodSync(join(outDir, "cli.js"), 0o755);
writeFileSync(
  join(outDir, "THIRD_PARTY_NOTICES.md"),
  `# Third-party notices\n\n\`dist/npm/cli.js\` bundles the following packages.\n\n${notices.join("\n")}`,
);
console.log(`built ${join(outDir, "cli.js")} (${(header + code).length} bytes)`);
